"""Generate the confirmed functional review from canonical YAML and its ledger."""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ocf_tools.canonical_integrity import verify as verify_canonical  # noqa: E402
from ocf_tools.commands import command_view  # noqa: E402
from ocf_tools.functional_metadata import record  # noqa: E402
from ocf_tools.indexes import load_all_functions  # noqa: E402
from ocf_tools.paths import REPO_ROOT  # noqa: E402
from ocf_tools.utils import OCFError, write_text_atomic  # noqa: E402


def build():
    problems = verify_canonical()
    if problems:
        raise OCFError("functional metadata integrity: " + " | ".join(problems))
    ledger = record()
    ids = {row["function_id"] for row in ledger["decisions"]}
    return {
        "id": ledger["id"],
        "source_commit": ledger["source_commit"],
        "confirmation": ledger["confirmation"],
        "reviewed": len(ledger["decisions"]),
        "approved": len(ledger["decisions"]),
        "deferred": [],
        "narration_changed": 0,
        "narration_unchanged": len(
            json.loads(
                (REPO_ROOT / "tests/fixtures/hplus-narration-text-baseline-008.json").read_text()
            )
        ),
        "runtime_policy": ledger["runtime_policy"],
        "locales_requiring_review": ledger["locales_requiring_review"],
        "functions": [
            {
                "id": owner.id,
                "title": owner.canonical_name,
                "purpose": owner.purpose_summary,
                "lifecycle": owner.data["lifecycle"],
                "commands": [command_view(owner, command) for command in owner.command_records],
                "issues": [
                    row["issue_id"] for row in ledger["decisions"] if row["function_id"] == owner.id
                ],
            }
            for owner in load_all_functions()
            if owner.id in ids
        ],
    }


def render(data):
    lines = [
        "# Current functional metadata review",
        "",
        "Generated by `scripts/tools/current_functional_metadata.py`; do not edit by hand.",
        "",
        f"{data['id']}: {data['approved']} explicitly approved decisions across {len(data['functions'])} functions.",
        "",
        "Historical metadata decision confirmation: **Please do**. That metadata-only decision left all 177 resolved narration entries unchanged. The subsequent source-only approved editorial batch is documented separately in [the editorial batch report](APPROVED_EDITORIAL_BATCH_20261114.md); it does not grant audio or publication approval.",
        "",
        data["runtime_policy"],
        "",
        "See [scope semantics](../FUNCTIONAL_METADATA.md). Functional metadata decision notes, provenance hashes, and their current values are stored with each canonical locale resource; this report is derived.",
        "",
    ]
    for function in data["functions"]:
        life = function["lifecycle"]
        lines.extend(
            [
                f"## {function['id']} — {function['title']}",
                "",
                function["purpose"],
                "",
                f"Function summary: `{life['persistence']}` / `{life['activation']}`; triggers: `{json.dumps(life.get('trigger_conditions', []))}`.",
                "",
            ]
        )
        for kind, scope in life.get("scopes", {}).items():
            lines.append(f"- **{kind}** (`{scope['persistence']}`): {scope['description']}")
        if life.get("scopes"):
            lines.append("")
        for command in function["commands"]:
            if command.get("availability") == "historical-lookup":
                continue
            invocation = command.get("invocation_scope", {})
            lines.append(
                f"- `{command['id']}`: `{command['phrase']}`; role `{command['role']}`; effect `{command.get('effect_scope', 'unspecified')}`; invocation `{invocation.get('activation', life['activation'])}` / `{invocation.get('persistence', 'unspecified')}`."
            )
        lines.append("")
    lines.extend(
        [
            "## Localization and audio",
            "",
            "English purpose, role and scope descriptions are synchronized with canonical YAML. Partial Spanish requires descriptive terminology review; no production translation was changed. For that historical metadata-only decision, speech inputs, templates, DSP, pacing, gains, repetitions and recording text fingerprints were unchanged. Subsequent source editorial changes do not update historical recording fingerprints. The current catalog has 58 source plans and preserves the separate 55-function historical cohort.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = build()
    outputs = {
        "docs/releases/OCF_FUNCTIONAL_METADATA_CURRENT.json": json.dumps(
            data, ensure_ascii=False, indent=2
        )
        + "\n",
        "docs/releases/OCF_FUNCTIONAL_METADATA_CURRENT.md": render(data),
    }
    for name, text in outputs.items():
        path = REPO_ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise OCFError("stale functional metadata report: " + name)
        else:
            write_text_atomic(path, text)
    print(
        json.dumps(
            {
                "reviewed": data["reviewed"],
                "functions": len(data["functions"]),
                "narration_unchanged": 177,
                "fresh": True,
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
